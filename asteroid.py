def create_sequences(data, feature_cols, target_col, timesteps=122):
    sequences, labels = [], []
    for _, group in data.groupby('spkid'):
        seq = group[feature_cols].values
        label = group[target_col].values[0] # Ambil 1 label target karena targetnya level asteroid

        # Zero padding jika sequence kurang dari timesteps
        if len(seq) >= timesteps:
            sequences.append(seq[-timesteps:])
        else:
            pad_len = timesteps - len(seq)
            pad_array = np.zeros((pad_len, len(feature_cols)))
            sequences.append(np.vstack((pad_array, seq)))
        labels.append(label)
    return np.array(sequences), np.array(labels)

