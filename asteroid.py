# Model 4: Transformer Encoder (Self-Attention untuk Orbital Parameters)
def build_transformer():
    inputs = Input(shape=input_shape) # Bentuk awal: (None, 122, 9)

    # 1. Projection Layer (Wajib agar dimensi seragam untuk Residual Connection)
    d_model = 64
    x = Dense(d_model)(inputs) # Mengubah fitur dari 9 menjadi 64 -> (None, 122, 64)

    # 2. Self Attention Block
    # key_dim diatur sama dengan d_model
    attn_output = MultiHeadAttention(key_dim=d_model, num_heads=4)(x, x)
    attn_output = Dropout(0.2)(attn_output)
    # Residual connection: 64 + 64 (Aman)
    x = LayerNormalization(epsilon=1e-6)(x + attn_output)

    # 3. Feed Forward Block
    # Ekspansi dimensi lalu proyeksikan kembali ke d_model
    x_ff = Dense(128, activation='relu')(x)
    x_ff = Dense(d_model)(x_ff)
    x_ff = Dropout(0.2)(x_ff)
    # Residual connection: 64 + 64 (Aman)
    x = LayerNormalization(epsilon=1e-6)(x + x_ff)

    # 4. Aggregation & Output
    x = GlobalAveragePooling1D()(x)
    x = Dense(16, activation='relu')(x)
    outputs = Dense(1, activation='sigmoid')(x)

    model = Model(inputs=inputs, outputs=outputs)
    model.compile(optimizer='adam', loss=focal_loss(), metrics=['accuracy', tf.keras.metrics.AUC(name='pr_auc', curve='PR')])
    return model

